export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { id, en }

export type TFn = (key: MessageKey, vars?: Record<string, string | number>) => string

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = MESSAGES[locale]?.[key] ?? MESSAGES.id[key] ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`))
  return s
}
